export function loadStoryLang() {
  try {
    const v = localStorage.getItem(STORY_LANG_KEY);
    return v === 'it' ? 'it' : 'blend';
  } catch {
    return 'blend';
  }
}

export function saveStoryLang(lang) {
  try {
    localStorage.setItem(STORY_LANG_KEY, lang);
  } catch {
    /* ignore */
  }
}

/** Merge Italian story record with EN·RU blend fields when lang is blend */
export function resolveStory(story, lang = 'blend') {
  if (!story || lang === 'it') return story;
  const blend = STORY_BLEND[story.id];
  if (!blend) return story;
  return {
    ...story,
    tag: blend.tag ?? story.tag,
    year: blend.year ?? story.year,
    title: blend.title ?? story.title,
    subtitle: blend.subtitle ?? story.subtitle,
    excerpt: blend.excerpt ?? story.excerpt,
    body: blend.body ?? story.body,
    readTime: blend.readTime ?? story.readTime,
    pullQuote: blend.pullQuote,
    cta: blend.cta,
    _lang: 'blend',
  };
}

